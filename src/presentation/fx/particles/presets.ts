// 默认 count 取分镜里最常用的那个数；调用方改 count 时，预设里每层（除了标 fixed 的闪光、冲击环）按比例缩放。
//
// 配色按分镜表 1.8 的颜色表，风格对着 LoL 的技能特效：亮核接近白色，往外是饱和的主色，尾巴压暗；
// 胜利碎屑用海克斯金、奶白和一点海克斯青，不用彩虹色。
//
// 尺寸参照：随从底座 1.5 宽、0.32 高；镜头约 21 单位远，1080p 下 1 单位约 75 像素。
// 落点 at 是物件脚下台面上的点：贴地的效果（扬尘、霜、烟、光环）发射半径至少 0.8，在底座外面，否则被底座挡住；
// 朝镜头的烟团中心至少抬到 0.3 倍大小以上，否则下半截插进台面被深度裁掉。
