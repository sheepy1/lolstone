// 默认参数下每个预设最多同时有多少粒子（各层数量之和，不计随机浮动），性能测试挑"最重"的用
export function presetParticleCount(name: PresetName, count?: number): number {
  const def = PRESETS[name];
  const ratio = (count ?? def.count) / def.count;
  return def.layers.reduce((n, l) => n + (l.fixed ? l.count : Math.round(l.count * ratio)), 0);
}

